// Generates the two time-zone data files from one IANA tzdata release, so
// they always agree:
//
//   src/data/zoneCoordinates.ts  each zone's principal location, from zone.tab
//                                — the sky of a card with no coordinates
//                                (spec §9.2)
//   src/data/zoneLinks.ts        old and merged names → the current name, from
//                                `backward` — canonicalZone() / sameZone()
//                                (spec §4.2)
//
//   node scripts/build-zone-data.mjs            latest tzdata release
//   node scripts/build-zone-data.mjs 2026d      a specific release
//
// Needs network access and `tar`. The output is committed; building the
// extension never runs this. Neither file holds an offset: every offset is
// still computed per date by Intl.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const release = process.argv[2];
const url = release
  ? `https://data.iana.org/time-zones/releases/tzdata${release}.tar.gz`
  : 'https://data.iana.org/time-zones/tzdata-latest.tar.gz';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'skies-tzdata-'));
try {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  fs.writeFileSync(path.join(dir, 'tzdata.tar.gz'), Buffer.from(await response.arrayBuffer()));
  execFileSync('tar', ['-xzf', 'tzdata.tar.gz', 'version', 'zone.tab', 'backward'], { cwd: dir });
  const version = fs.readFileSync(path.join(dir, 'version'), 'utf8').trim();
  const source = `IANA tzdata ${version}\n// (https://data.iana.org/time-zones/releases/tzdata${version}.tar.gz) — do not edit by hand.\n// Regenerate: node scripts/build-zone-data.mjs ${version}`;

  // ISO 6709: ±DDMM±DDDMM or ±DDMMSS±DDDMMSS.
  const angle = (text, degreeDigits) => {
    const sign = text[0] === '-' ? -1 : 1;
    const d = +text.slice(1, 1 + degreeDigits);
    const m = +text.slice(1 + degreeDigits, 3 + degreeDigits);
    const s = +(text.slice(3 + degreeDigits) || 0);
    return sign * (d + m / 60 + s / 3600);
  };
  const coordinates = new Map();
  for (const line of fs.readFileSync(path.join(dir, 'zone.tab'), 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const [, iso, zone] = line.split('\t');
    const [, lat, lon] = iso.match(/^([+-]\d+)([+-]\d+)$/);
    coordinates.set(zone, [angle(lat, 2), angle(lon, 3)]);
  }

  // `backward` links old names (Asia/Calcutta) to current ones, but also
  // merged zones to the zone they share rules with (Africa/Accra →
  // Africa/Abidjan, Europe/Oslo → Europe/Berlin). A name zone.tab lists is
  // the one its country uses now, so it is left alone: a Ghanaian's System
  // chip reads Accra, not Abidjan.
  const targets = new Map();
  for (const line of fs.readFileSync(path.join(dir, 'backward'), 'utf8').split('\n')) {
    const match = line.match(/^Link\s+(\S+)\s+(\S+)/);
    if (match) targets.set(match[2], match[1]);
  }
  const links = new Map();
  for (const name of targets.keys()) {
    if (coordinates.has(name)) continue;
    let current = name;
    for (let hops = 0; targets.has(current) && hops < 10; hops++) current = targets.get(current);
    links.set(name, current);
  }

  const round = (n) => Math.round(n * 100) / 100;
  const sorted = (map) => [...map].sort(([a], [b]) => (a < b ? -1 : 1));
  fs.mkdirSync(path.join(root, 'src/data'), { recursive: true });
  fs.writeFileSync(
    path.join(root, 'src/data/zoneCoordinates.ts'),
    `// GENERATED by scripts/build-zone-data.mjs from ${source}
//
// [latitude, longitude] of each zone's principal location, from zone.tab
// (${coordinates.size} zones). Old names reach these through canonicalZone()
// (zoneLinks.ts, same release). Location data, not offsets: every offset is
// still computed per date by Intl (spec §4.2).
export const ZONE_COORDINATES: Readonly<Record<string, readonly [number, number]>> = {
${sorted(coordinates)
  .map(([zone, [lat, lon]]) => `  '${zone}': [${round(lat)}, ${round(lon)}],`)
  .join('\n')}
};
`
  );
  fs.writeFileSync(
    path.join(root, 'src/data/zoneLinks.ts'),
    `// GENERATED by scripts/build-zone-data.mjs from ${source}
//
// Old and merged zone names → the current name, from \`backward\` (${links.size} names).
// Names zone.tab still lists are current and not here, even when \`backward\`
// links them to a zone they share rules with (Africa/Accra, Europe/Oslo).
// Names only, no offsets (spec §4.2).
export const ZONE_LINKS: Readonly<Record<string, string>> = {
${sorted(links)
  .map(([name, current]) => `  '${name}': '${current}',`)
  .join('\n')}
};
`
  );
  console.log(`src/data/: tzdata ${version} — zoneCoordinates.ts ${coordinates.size} zones, zoneLinks.ts ${links.size} names`);
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}
