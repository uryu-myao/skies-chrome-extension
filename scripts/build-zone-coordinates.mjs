// Generates src/data/zoneCoordinates.ts from IANA tzdata: the coordinates
// zone.tab gives each time zone's principal location, plus every old name in
// `backward` that links to one of those zones. The popup uses them to colour
// the sky of a card that has no coordinates of its own (spec §9.2).
//
//   node scripts/build-zone-coordinates.mjs            latest tzdata release
//   node scripts/build-zone-coordinates.mjs 2026a      a specific release
//
// Needs network access and `tar`. The output is committed; building the
// extension never runs this.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const release = process.argv[2];
const url = release
  ? `https://data.iana.org/time-zones/releases/tzdata${release}.tar.gz`
  : 'https://data.iana.org/time-zones/tzdata-latest.tar.gz';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'skies-tzdata-'));
try {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  fs.writeFileSync(path.join(dir, 'tzdata.tar.gz'), Buffer.from(await response.arrayBuffer()));
  execFileSync('tar', ['-xzf', 'tzdata.tar.gz', 'version', 'zone.tab', 'backward'], { cwd: dir });
  const version = fs.readFileSync(path.join(dir, 'version'), 'utf8').trim();

  // ISO 6709: ±DDMM±DDDMM or ±DDMMSS±DDDMMSS.
  const angle = (text, degreeDigits) => {
    const sign = text[0] === '-' ? -1 : 1;
    const d = +text.slice(1, 1 + degreeDigits);
    const m = +text.slice(1 + degreeDigits, 3 + degreeDigits);
    const s = +(text.slice(3 + degreeDigits) || 0);
    return sign * (d + m / 60 + s / 3600);
  };
  const coordinates = new Map();
  for (const line of fs.readFileSync(path.join(dir, 'zone.tab'), 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const [, iso, zone] = line.split('\t');
    const [, lat, lon] = iso.match(/^([+-]\d+)([+-]\d+)$/);
    coordinates.set(zone, [angle(lat, 2), angle(lon, 3)]);
  }
  const zoneCount = coordinates.size;
  let linkCount = 0;
  for (const line of fs.readFileSync(path.join(dir, 'backward'), 'utf8').split('\n')) {
    const match = line.match(/^Link\s+(\S+)\s+(\S+)/);
    if (!match) continue;
    const [, target, name] = match;
    if (coordinates.has(target) && !coordinates.has(name)) {
      coordinates.set(name, coordinates.get(target));
      linkCount++;
    }
  }

  const round = (n) => Math.round(n * 100) / 100;
  const rows = [...coordinates]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([zone, [lat, lon]]) => `  '${zone}': [${round(lat)}, ${round(lon)}],`);
  const out = `// GENERATED by scripts/build-zone-coordinates.mjs from IANA tzdata ${version}
// (https://data.iana.org/time-zones/releases/tzdata${version}.tar.gz) — do not edit by hand.
// Regenerate: node scripts/build-zone-coordinates.mjs ${version}
//
// [latitude, longitude] of each zone's principal location, from zone.tab
// (${zoneCount} zones), and of the zone each old name in \`backward\` links to (${linkCount} names).
// This is location data, not offsets: every offset is still computed per date
// by Intl (spec §4.2).
export const ZONE_COORDINATES: Readonly<Record<string, readonly [number, number]>> = {
${rows.join('\n')}
};
`;
  fs.mkdirSync(path.join(root, 'src/data'), { recursive: true });
  fs.writeFileSync(path.join(root, 'src/data/zoneCoordinates.ts'), out);
  console.log(`src/data/zoneCoordinates.ts: tzdata ${version}, ${zoneCount} zones + ${linkCount} links`);
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}
